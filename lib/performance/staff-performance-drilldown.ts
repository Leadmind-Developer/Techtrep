import {
  LeadStatus,
  OpportunityStatus,
} from "@/generated/prisma/client";

import { prisma } from "@/lib/prisma";

import type { PerformancePeriod } from "./staff-performance";

export type PerformanceDrilldownMetric =
  | "leads-generated"
  | "qualified-leads"
  | "opportunities-created"
  | "opportunities-won"
  | "opportunities-lost"
  | "open-opportunities"
  | "activities";

export type PerformanceDrilldownRecord = {
  id: string;
  type:
    | "lead"
    | "opportunity"
    | "activity";
  title: string;
  subtitle: string | null;
  status: string | null;
  value: number | null;
  createdAt: Date;
  closedAt: Date | null;
};

export type PerformanceDrilldownResult = {
  metric: PerformanceDrilldownMetric;
  records: PerformanceDrilldownRecord[];
  total: number;
  page: number;
  pageSize: number;
  totalPages: number;
};

const DEFAULT_PAGE_SIZE = 25;
const MAX_PAGE_SIZE = 100;

function normalizePagination(
  page: number,
  pageSize: number,
) {
  const normalizedPage =
    Number.isFinite(page) && page > 0
      ? Math.floor(page)
      : 1;

  const normalizedPageSize =
    Number.isFinite(pageSize) && pageSize > 0
      ? Math.min(
          Math.floor(pageSize),
          MAX_PAGE_SIZE,
        )
      : DEFAULT_PAGE_SIZE;

  return {
    page: normalizedPage,
    pageSize: normalizedPageSize,
  };
}

function getDateRangeFilter(
  period: PerformancePeriod,
) {
  return {
    gte: period.from,
    lt: period.to,
  };
}

function toNumber(
  value:
    | {
        toNumber(): number;
      }
    | number
    | null,
): number | null {
  if (value === null) {
    return null;
  }

  return typeof value === "number"
    ? value
    : value.toNumber();
}

function assignmentCoversTimestamp(
  assignment: {
    assignedAt: Date;
    unassignedAt: Date | null;
  },
  timestamp: Date,
): boolean {
  return (
    assignment.assignedAt <= timestamp &&
    (
      assignment.unassignedAt === null ||
      assignment.unassignedAt > timestamp
    )
  );
}

/**
 * Return leads generated by a staff member
 * during the selected performance period.
 *
 * Attribution is based on the user who created
 * the lead, not its current owner.
 */
async function getGeneratedLeads(
  userId: string,
  period: PerformancePeriod,
  page: number,
  pageSize: number,
): Promise<PerformanceDrilldownResult> {
  const dateRange =
    getDateRangeFilter(period);

  const where = {
    createdByUserId: userId,
    createdAt: dateRange,
  };

  const [total, leads] =
    await Promise.all([
      prisma.lead.count({
        where,
      }),

      prisma.lead.findMany({
        where,
        select: {
          id: true,
          status: true,
          createdAt: true,
          organization: {
            select: {
              name: true,
            },
          },
          contact: {
            select: {
              name: true,
            },
          },
        },
        orderBy: {
          createdAt: "desc",
        },
        skip:
          (page - 1) * pageSize,
        take: pageSize,
      }),
    ]);

  return {
    metric: "leads-generated",
    records: leads.map((lead) => ({
      id: lead.id,
      type: "lead",
      title:
        lead.organization.name,
      subtitle:
        lead.contact?.name ?? null,
      status: lead.status,
      value: null,
      createdAt: lead.createdAt,
      closedAt: null,
    })),
    total,
    page,
    pageSize,
    totalPages:
      Math.ceil(total / pageSize),
  };
}


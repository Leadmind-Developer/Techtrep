export async function getStaffPerformanceDrilldown(
  userId: string,
  metric: PerformanceDrilldownMetric,
  period: PerformancePeriod,
  page = 1,
  pageSize = DEFAULT_PAGE_SIZE,
): Promise<PerformanceDrilldownResult> {
  const pagination =
    normalizePagination(
      page,
      pageSize,
    );

  switch (metric) {
    case "leads-generated":
      return getGeneratedLeads(
        userId,
        period,
        pagination.page,
        pagination.pageSize,
      );

    case "qualified-leads":
      return getQualifiedLeads(
        userId,
        period,
        pagination.page,
        pagination.pageSize,
      );

    case "opportunities-created":
      return getCreatedOpportunities(
        userId,
        period,
        pagination.page,
        pagination.pageSize,
      );

    case "opportunities-won":
      return getWonOpportunities(
        userId,
        period,
        pagination.page,
        pagination.pageSize,
      );

    case "opportunities-lost":
      return getLostOpportunities(
        userId,
        period,
        pagination.page,
        pagination.pageSize,
      );

    case "open-opportunities":
      return getOpenOpportunities(
        userId,
        period,
        pagination.page,
        pagination.pageSize,
      );

    case "activities":
      return getActivities(
        userId,
        period,
        pagination.page,
        pagination.pageSize,
      );
  }
}
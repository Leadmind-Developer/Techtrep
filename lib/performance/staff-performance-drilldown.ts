/**
 * Return opportunities won by a staff member
 * during the selected period.
 *
 * The performance date is closedAt.
 * Ownership is determined from assignment history
 * at the exact close timestamp.
 */
async function getWonOpportunities(
  userId: string,
  period: PerformancePeriod,
  page: number,
  pageSize: number,
): Promise<PerformanceDrilldownResult> {
  const dateRange =
    getDateRangeFilter(period);

  const where = {
    closedAt: dateRange,
    status: "WON" as const,
  };

  const [allMatching,] =
    await Promise.all([
      prisma.opportunity.findMany({
        where,
        select: {
          id: true,
          name: true,
          description: true,
          status: true,
          estimatedValue: true,
          createdAt: true,
          closedAt: true,
          assignments: {
            select: {
              assignedToUserId: true,
              assignedAt: true,
              unassignedAt: true,
            },
            orderBy: {
              assignedAt: "asc",
            },
          },
          auditRequest: {
            select: {
              organization: {
                select: {
                  name: true,
                },
              },
            },
          },
        },
        orderBy: {
          closedAt: "desc",
        },
      }),
    ]);

  const matching = allMatching.filter(
    (opportunity) => {
      const closedAt = opportunity.closedAt;

      if (!closedAt) {
        return false;
      }

      return opportunity.assignments.some(
        (assignment) =>
          assignment.assignedToUserId === userId &&
          assignmentCoversTimestamp(
            assignment,
            closedAt,
          ),
      );
    },
  );

  const total = matching.length;

  const opportunities = matching.slice(
    (page - 1) * pageSize,
    page * pageSize,
  );

  return {
    metric: "opportunities-won",
    records: opportunities.map(
      (opportunity) => ({
        id: opportunity.id,
        type: "opportunity",
        title: opportunity.name,
        subtitle:
          opportunity.auditRequest
            .organization.name,
        status: opportunity.status,
        value: toNumber(
          opportunity.estimatedValue,
        ),
        createdAt:
          opportunity.createdAt,
        closedAt:
          opportunity.closedAt,
      }),
    ),
    total,
    page,
    pageSize,
    totalPages:
      Math.ceil(total / pageSize),
  };
}

